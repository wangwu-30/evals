import assert from 'node:assert/strict';
import {units,dice,align,threeWay,defaultRun,files,wordDiff,sentences,quoteRange} from './core.mjs';
assert.equal(units("你好 world 123 don't A-1"),6);
assert.equal(dice('same','same'),1);
const a=['shared sentence.','only left.'],b=['shared sentence.','completely different 中文'];
const rows=align(a,b);
assert.deepEqual(rows.filter(r=>r[0]!=null).map(r=>r[0]),a);
assert.deepEqual(rows.filter(r=>r[1]!=null).map(r=>r[1]),b);
const three=threeWay(a,[b,['prefix',...a]]);
assert.deepEqual(three.filter(r=>r[0]!=null).map(r=>r[0]),a);
assert.deepEqual(three.filter(r=>r[2]!=null).map(r=>r[2]),['prefix',...a]);
assert.equal(defaultRun([{rep:0,text:'',len_units:0},{rep:1,text:'a b',len_units:2},{rep:2,text:'a b c d',len_units:4}]).rep,1);
assert.equal(defaultRun([{rep:0,text:'wrong answer',len_units:2,correct:0},{rep:1,text:'right',len_units:1,correct:1}],true).rep,0);
assert.deepEqual(files('=== FILE: a.py ===\na\n=== FILE: b.py ===\nb'),{'a.py':'a\n','b.py':'b'});
const diff=wordDiff('共同开头 old 共同结尾','共同开头 new 共同结尾');
assert.equal(diff.filter(x=>x.kind!=='add').map(x=>x.text).join(''),'共同开头 old 共同结尾');
assert.equal(diff.filter(x=>x.kind!=='del').map(x=>x.text).join(''),'共同开头 new 共同结尾');
const text='你好。\nSecond sentence. Third!\n';
assert.equal(sentences(text).join(''),text);
assert.deepEqual(quoteRange('First. Second. Third.','First. Second.','Second.'),[0,7]);
assert.equal(quoteRange('First. Second.','not present','First.'),null);
assert.equal(defaultRun([{rep:1,has_text:true,text:'',len_units:4},{rep:0,text:'',len_units:0}]).rep,1);
console.log('13 viewer core assertions passed');
